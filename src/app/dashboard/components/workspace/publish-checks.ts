/* ── Where a page's head is ────────────────────────────────────────────────
 *
 * A title or description counts only where a browser and a search engine read
 * it: inside <head> of an HTML page, or in the `metadata` a Next.js layout or
 * page exports (or <Head> in the pages router). A `title: "…"` in a list of
 * feature cards is not the page's title, and it used to count as one. */

/* Titles a starter template ships with: present, and still not the site's. */
const STARTER_TITLE = /^(document|untitled|home|title|my (website|app|site)|react app|vite \+ react(\s*\+\s*ts)?|vite app|create next app|next\.?js app|new project|index)$/i;
const STARTER_DESCRIPTION = /^(generated by create next app|web site created using create-react-app|description)$/i;

/* The text of a `{ … }` block starting at `start` (the "{"), braces balanced. */
function blockAt(text: string, start: number): string {
  let depth = 0;
  let inQuote: string | null = null;
  for (let i = start; i < text.length; i += 1) {
    const char = text[i];
    if (inQuote) {
      if (char === "\\") i += 1;
      else if (char === inQuote) inQuote = null;
    } else if (char === '"' || char === "'" || char === "`") inQuote = char;
    else if (char === "{") depth += 1;
    else if (char === "}") {
      depth -= 1;
      if (depth === 0) return text.slice(start, i + 1);
    }
  }
  return text.slice(start, Math.min(text.length, start + 4000));
}

type Head = { file: string; title: string | null; description: string | null; icon: string | null; share: boolean };

/* What each page head says. One entry per file that has a head of its own. */
function heads(files: File[]): Head[] {
  const out: Head[] = [];
  for (const file of files) {
    if (/node_modules\//.test(file.path)) continue;
    const text = file.content;
    if (/\.html?$/i.test(file.path)) {
      const head = /<head[\s>][\s\S]*?<\/head>/i.exec(text)?.[0];
      if (!head) continue;
      out.push({
        file: file.path,
        title: /<title[^>]*>([^<]*)<\/title>/i.exec(head)?.[1]?.trim() || null,
        description: /<meta[^>]+name=["']description["'][^>]*content=["']([^"']*)["']|<meta[^>]+content=["']([^"']*)["'][^>]*name=["']description["']/i
          .exec(head)
          ?.slice(1)
          .find(Boolean)
          ?.trim() || null,
        icon: /<link[^>]+rel=["'][^"']*\bicon\b[^"']*["'][^>]*href=["']([^"']+)["']|<link[^>]+href=["']([^"']+)["'][^>]*rel=["'][^"']*\bicon\b/i
          .exec(head)
          ?.slice(1)
          .find(Boolean) ?? null,
        share: /property=["']og:image["']|name=["']twitter:image["']/i.test(head),
      });
      continue;
    }
    if (!/\.[jt]sx?$/.test(file.path)) continue;
    /* App router: export const metadata = { … } or generateMetadata. */
    const at = /export\s+const\s+metadata\b[^=]*=\s*\{/.exec(text) ?? /export\s+(?:async\s+)?function\s+generateMetadata[\s\S]*?return\s*\{/.exec(text);
    if (at) {
      const block = blockAt(text, at.index + at[0].length - 1);
      const string = (key: string) =>
        new RegExp(`\\b${key}\\s*:\\s*(?:["'\`]([^"'\`]*)["'\`]|\\{[^}]*default\\s*:\\s*["'\`]([^"'\`]*)["'\`])`).exec(block)?.slice(1).find((v) => v !== undefined)?.trim() || null;
      out.push({
        file: file.path,
        title: string("title"),
        description: string("description"),
        icon: /\bicons?\s*:/.test(block) ? "metadata" : null,
        share: /\bopenGraph\s*:[\s\S]*?\bimages?\s*:|\btwitter\s*:[\s\S]*?\bimages?\s*:/.test(block),
      });
      continue;
    }
    /* Pages router: <Head><title>…</title></Head>. */
    const nextHead = /<Head>([\s\S]*?)<\/Head>/.exec(text)?.[1];
    if (nextHead) {
      out.push({
        file: file.path,
        title: /<title>\s*\{?["'`]?([^<{}"'`]+)["'`]?\}?\s*<\/title>/.exec(nextHead)?.[1]?.trim() || null,
        description: /name=["']description["'][^>]*content=\{?["'`]([^"'`]*)/.exec(nextHead)?.[1]?.trim() || null,
        icon: /rel=["'][^"']*icon/.exec(nextHead) ? "head" : null,
        share: /og:image/.test(nextHead),
      });
    }
  }
  return out;
}

/* The head that speaks for the whole site: the root layout, else the home
   page, else the first page with a head. */
function siteHead(all: Head[]): Head | null {
  const rank = (path: string) =>
    /^(src\/)?app\/layout\.[jt]sx?$/.test(path) ? 0
      : /^(src\/)?pages\/_(app|document)\.[jt]sx?$/.test(path) ? 1
        : /^(public\/)?index\.html?$/.test(path) ? 2
          : /^(src\/)?app\/page\.[jt]sx?$/.test(path) ? 3
            : 9;
  return [...all].sort((a, b) => rank(a.file) - rank(b.file))[0] ?? null;
}

/* A named handler's body: `function name(…) { … }` or `const name = (…) => { … }`. */
function handlerBody(text: string, name: string): string | null {
  const escaped = name.replace(/[$]/g, "\\$");
  const at =
    new RegExp(`function\\s+${escaped}\\s*\\([^)]*\\)\\s*(?::[^{]+)?\\{`).exec(text) ??
    new RegExp(`(?:const|let)\\s+${escaped}\\s*=\\s*(?:async\\s*)?(?:\\([^)]*\\)|[A-Za-z_$][\\w$]*)\\s*(?::[^=]+)?=>\\s*\\{`).exec(text) ??
    new RegExp(`(?:const|let)\\s+${escaped}\\s*=\\s*(?:async\\s*)?function\\b[^{]*\\{`).exec(text);
  return at ? blockAt(text, at.index + at[0].length - 1) : null;
}

/* Whether code actually sends what was typed somewhere. A handler that only
   stops the reload, sets a "thanks" flag or shows an alert pretends to. */
const SENDS = /\bfetch\s*\(|axios|\.insert\s*\(|\.upsert\s*\(|\.rpc\s*\(|supabase|\.from\s*\(\s*["'`]|emailjs|formspree|formsubmit|web3forms|getform|\bmutate(Async)?\s*\(|\bsubmit[A-Z]\w*\s*\(|\bsend[A-Z]\w*\s*\(|\bcreate[A-Z]\w*\s*\(|\bsave[A-Z]\w*\s*\(|\bpost[A-Z]?\w*\s*\(|router\.push|navigator\.sendBeacon|mailto:|window\.location/;

function formSends(file: string, tag: string, inner: string): boolean {
  const action = /\baction\s*=\s*(?:["']([^"']*)["']|\{([^}]*)\})/.exec(tag);
  if (action) {
    const value = (action[1] ?? action[2] ?? "").trim();
    if (action[2] !== undefined) return value.length > 0; // a server action or a variable
    if (value && value !== "#" && !/^javascript:/i.test(value)) return true;
  }
  if (/\bdata-netlify\b|netlify\s*=|formspree|formsubmit|web3forms|getform/i.test(tag)) return true;
  if (/\{\s*\.\.\./.test(tag)) return true; // spread props: the caller wires it
  const handler = /\bonSubmit\s*=\s*\{([\s\S]*)\}/.exec(tag)?.[1]?.trim();
  if (handler) {
    if (SENDS.test(handler)) return true;
    /* handleSubmit(onSubmit) from react-hook-form, or a plain name. */
    const name = /handleSubmit\s*\(\s*([A-Za-z_$][\w$]*)/.exec(handler)?.[1] ?? /^([A-Za-z_$][\w$]*)$/.exec(handler)?.[1];
    if (name) {
      const body = handlerBody(file, name);
      return body ? SENDS.test(body) : true; // defined elsewhere (a prop): trust it
    }
    return false; // an inline handler that sends nothing
  }
  /* No handler on the form: a button inside doing the work. */
  const click = /<button\b[^>]*\bonClick\s*=\s*\{([^}]*)\}/.exec(inner)?.[1]?.trim();
  if (click) {
    if (SENDS.test(click)) return true;
    const body = /^[A-Za-z_$][\w$]*$/.test(click) ? handlerBody(file, click) : null;
    return body ? SENDS.test(body) : !/^\(\)\s*=>/.test(click);
  }
  return false;
}

