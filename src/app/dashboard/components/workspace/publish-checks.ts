/* Visible text only: tags, code and comments taken out. */
function visibleText(content: string): string {
  return content
    .replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/gi, " ")
    .replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, " ")
    .replace(/<[^>]+>/g, " ");
}

/* The pages a link can reach: Next.js routes, and the HTML files. */
function routes(files: File[]): Set<string> {
  const found = new Set<string>(["/"]);
  for (const file of files) {
    const path = file.path.replace(/^\/+/, "");
    const app = /^(?:src\/)?app\/(.*?)\/?page\.[jt]sx?$/.exec(path);
    if (app) {
      const route = "/" + app[1].split("/").filter((part) => part && !/^\(.*\)$/.test(part) && !part.startsWith("@")).join("/");
      found.add(route === "/" ? "/" : route.replace(/\/$/, ""));
      continue;
    }
    const pagesRoute = /^(?:src\/)?pages\/(.+)\.[jt]sx?$/.exec(path);
    if (pagesRoute && !/^(_|api\/)/.test(pagesRoute[1])) {
      found.add("/" + pagesRoute[1].replace(/(^|\/)index$/, "").replace(/\/$/, ""));
      continue;
    }
    if (/\.html?$/i.test(path)) {
      const clean = path.replace(/^public\//, "");
      found.add("/" + clean);
      found.add("/" + clean.replace(/\.html?$/i, ""));
      if (/(^|\/)index\.html?$/i.test(clean)) found.add("/" + clean.replace(/index\.html?$/i, "").replace(/\/$/, ""));
    }
  }
  return found;
}

function routeExists(href: string, known: Set<string>): boolean {
  const path = href.split(/[?#]/)[0].replace(/\/$/, "") || "/";
  if (known.has(path)) return true;
  /* Dynamic segments: /blog/[slug] matches /blog/anything. */
  for (const route of known) {
    if (!route.includes("[")) continue;
    const pattern = new RegExp("^" + route.replace(/\[\[?\.\.\.[^\]]+\]\]?/g, ".*").replace(/\[[^\]]+\]/g, "[^/]+") + "$");
    if (pattern.test(path)) return true;
  }
  return false;
}

/** Images on the web that did not load — found by actually loading them. */
export async function findBrokenImages(files: File[], timeoutMs = 7000, most = 30): Promise<Set<string>> {
  const urls = new Set<string>();
  for (const file of pages(files)) {
    for (const match of file.content.matchAll(/\b(?:src|href|content)\s*=\s*["'](https?:\/\/[^"'\s]+?\.(?:png|jpe?g|gif|webp|svg|avif)(?:\?[^"'\s]*)?|https?:\/\/images\.unsplash\.com\/[^"'\s]+|https?:\/\/[^"'\s]*(?:pexels|pixabay|cloudinary|imgix)[^"'\s]*)["']/gi)) {
      urls.add(match[1]);
      if (urls.size >= most) break;
    }
  }
  const broken = new Set<string>();
  if (typeof window === "undefined" || urls.size === 0) return broken;
  await Promise.all(
    [...urls].map(
      (url) =>
        new Promise<void>((resolve) => {
          const image = new Image();
          const timer = window.setTimeout(() => resolve(), timeoutMs); // slow is not broken
          image.onload = () => {
            window.clearTimeout(timer);
            resolve();
          };
          image.onerror = () => {
            window.clearTimeout(timer);
            broken.add(url);
            resolve();
          };
          image.src = url;
        }),
    ),
  );
  return broken;
}

export function runChecks(input: {
  files: File[];
  webApp: boolean;
  backend: BackendInfo;
  secretNames: string[] | null;
  /** Remote images that failed to load (findBrokenImages), when known. */
  brokenRemote?: Set<string>;
}): Check[] {
  const { files, webApp, backend, secretNames, brokenRemote } = input;
  const paths = new Set(files.map((file) => file.path.replace(/^\/+/, "")));
  const checks: Check[] = [];
  const head = siteHead(heads(files));
  const where = head?.file ?? headFile(files);
  const inHead = where ? `In ${where}, ` : "";

  /* ── Title and description, where search engines read them ───────────── */
  {
    const problems: string[] = [];
    if (!head?.title) problems.push("no page title");
    else if (STARTER_TITLE.test(head.title)) problems.push(`the title is still "${head.title}"`);
    if (!head?.description) problems.push("no description for search results");
    else if (STARTER_DESCRIPTION.test(head.description)) problems.push(`the description is still "${head.description}"`);
    else if (head.description.length < 50) problems.push("the description is too short to show in search results");
    checks.push(
      problems.length === 0
        ? { id: "seo", label: "Page title and description set", level: "pass" }
        : {
            id: "seo",
            label: "Page title and description set",
            level: "warn",
            detail: problems.join("; ").replace(/^./, (c) => c.toUpperCase()) + ".",
            fix: "chat",
            asks: [
              `${inHead}${problems.join(", and ")}. Set the site's page title (the business name and what it offers, under 60 characters) and a meta description of 120–160 characters, written from what the site is about — in the page's own <head> or exported metadata, not in its content.`,
            ],
          },
    );
  }

  /* ── Favicon and share image, in the head — and actually there ────────── */
  {
    const iconFile = [...paths].some((path) => /(^|\/)(app\/)?(favicon\.(ico|png|svg)|icon\.(png|svg|ico)|apple-icon\.png)$/i.test(path));
    let hasIcon = Boolean(head?.icon) || iconFile;
    /* A favicon link pointing at a file that is not there is no favicon. */
    if (head?.icon && head.icon !== "metadata" && head.icon !== "head" && !/^(https?:|data:)/.test(head.icon)) {
      const clean = head.icon.replace(/^\.?\//, "").split("?")[0];
      if (!paths.has(clean) && !paths.has(`public/${clean}`) && !iconFile) hasIcon = false;
    }
    const hasShare = Boolean(head?.share) || [...paths].some((path) => /(^|\/)(opengraph|twitter)-image\.(png|jpe?g)$/i.test(path));
    checks.push(
      hasIcon && hasShare
        ? { id: "icons", label: "Favicon and social share image", level: "pass" }
        : {
            id: "icons",
            label: "Favicon and social share image",
            level: "warn",
            detail: hasIcon ? "No share image for link previews." : hasShare ? "No favicon (the browser tab shows a blank icon)." : "No favicon or share image.",
            fix: "chat",
            asks: [
              `${inHead}${hasIcon ? "" : "add a favicon (an SVG icon in the brand colour with the first letter of the business name, linked as rel=\"icon\")"}${!hasIcon && !hasShare ? ", and " : ""}${hasShare ? "" : "add a social share image: og:image and twitter:image meta tags (1200×630) using the site's main hero image"}.`,
            ],
          },
    );
  }

  /* ── Forms that really send ──────────────────────────────────────────── */
  {
    const loose: Spot[] = [];
    let count = 0;
    for (const file of pages(files)) {
      for (const match of file.content.matchAll(/<form(?=[\s>])/g)) {
        count += 1;
        const start = match.index ?? 0;
        const tag = tagAt(file.content, start);
        const end = file.content.indexOf("</form>", start);
        const inner = end > start ? file.content.slice(start + tag.length, end) : "";
        if (!formSends(file.content, tag, inner)) loose.push({ path: file.path, line: lineOf(file.content, start), code: quote(tag) });
      }
    }
    if (count) {
      const byFile = new Map<string, Spot[]>();
      for (const spot of loose) byFile.set(spot.path, [...(byFile.get(spot.path) ?? []), spot]);
      checks.push(
        loose.length === 0
          ? { id: "forms", label: "Forms connected", level: "pass" }
          : {
              id: "forms",
              label: "Forms connected",
              level: "warn",
              detail: `${loose.length} form${loose.length === 1 ? " doesn't" : "s don't"} send anything — visitors would think they did: ${loose
                .slice(0, 3)
                .map((spot) => `${spot.path}:${spot.line}`)
                .join(", ")}${loose.length > 3 ? ` and ${loose.length - 3} more` : ""}`,
              fix: "chat",
              asks: [...byFile].map(
                ([path, spots]) =>
                  `In ${path}, ${spots.map((spot) => `the form at line ${spot.line} (\`${spot.code}\`)`).join(" and ")} ${
                    spots.length === 1 ? "doesn't" : "don't"
                  } send what is typed anywhere — the submit only stops the page reloading or shows a message. Make ${
                    spots.length === 1 ? "it" : "each"
                  } actually deliver the entry (save it to the site's form inbox, or email it), show a confirmation only once it has gone, and show an error if it fails.`,
              ),
            },
      );
    }
  }

  /* ── Images: missing files, placeholders, ones that do not load ──────── */
  {
    const missing: Spot[] = [];
    for (const file of pages(files)) {
      for (const match of file.content.matchAll(/\b(?:src|srcSet|href)\s*=\s*["']([^"'{}]*)["']/g)) {
        const src = match[1].trim();
        const line = lineOf(file.content, match.index ?? 0);
        const isImageAttr = /^src/i.test(match[0]) || /\.(png|jpe?g|gif|webp|svg|avif|ico)(\?|$)/i.test(src);
        if (!isImageAttr) continue;
        if (/^src/i.test(match[0]) && src === "") {
          missing.push({ path: file.path, line, code: 'src=""' });
          continue;
        }
        if (/(via\.placeholder\.com|placehold\.(co|it)|placeholder\.com|dummyimage\.com|example\.com\/.*\.(png|jpe?g))/i.test(src)) {
          missing.push({ path: file.path, line, code: src });
          continue;
        }
        if (brokenRemote?.has(src)) {
          missing.push({ path: file.path, line, code: src });
          continue;
        }
        if (!/\.(png|jpe?g|gif|webp|svg|avif|ico)(\?|$)/i.test(src) || /^(https?:|data:|\/\/|#|mailto:)/i.test(src)) continue;
        const clean = src.replace(/^\.?\//, "").split("?")[0];
        if (!paths.has(clean) && !paths.has(`public/${clean}`)) missing.push({ path: file.path, line, code: src });
      }
    }
    const byFile = new Map<string, Spot[]>();
    for (const spot of missing) byFile.set(spot.path, [...(byFile.get(spot.path) ?? []), spot]);
    checks.push(
      missing.length === 0
        ? { id: "images", label: "No broken images", level: "pass" }
        : {
            id: "images",
            label: "No broken images",
            level: "warn",
            detail: `${missing.length} image${missing.length === 1 ? "" : "s"} won't show: ${missing
              .slice(0, 3)
              .map((spot) => `${spot.code.length > 48 ? `${spot.code.slice(0, 45)}…` : spot.code} (${spot.path}:${spot.line})`)
              .join(", ")}${missing.length > 3 ? ` and ${missing.length - 3} more` : ""}`,
            fix: "chat",
            asks: [...byFile].map(
              ([path, spots]) =>
                `In ${path}, ${spots.map((spot) => `line ${spot.line} uses "${spot.code}"`).join(" and ")}, which ${
                  spots.length === 1 ? "doesn't" : "don't"
                } load (missing, empty or a placeholder). Replace ${spots.length === 1 ? "it" : "them"} with a real image that fits the section — an image already in the project, or a suitable stock photo URL.`,
            ),
          },
    );
  }

  /* ── Links that go nowhere ───────────────────────────────────────────── */
  {
    const known = routes(files);
    const ids = new Set<string>();
    for (const file of pages(files)) for (const match of file.content.matchAll(/\bid\s*=\s*["']([^"']+)["']/g)) ids.add(match[1]);
    const dead: Spot[] = [];
    for (const file of pages(files)) {
      for (const match of file.content.matchAll(/<(?:a|Link)\b[^>]*?\bhref\s*=\s*(?:["']([^"']*)["']|\{\s*["'`]([^"'`]*)["'`]\s*\})/g)) {
        const href = (match[1] ?? match[2] ?? "").trim();
        const line = lineOf(file.content, match.index ?? 0);
        if (href === "" || href === "#" || /^javascript:/i.test(href)) {
          dead.push({ path: file.path, line, code: `href="${href}"` });
        } else if (href.startsWith("#")) {
          if (!ids.has(href.slice(1))) dead.push({ path: file.path, line, code: `href="${href}"` });
        } else if (href.startsWith("/") && !href.startsWith("//") && !/\.(pdf|png|jpe?g|svg|zip|xml|txt|ico)(\?|$)/i.test(href)) {
          if (!routeExists(href, known)) dead.push({ path: file.path, line, code: `href="${href}"` });
        }
      }
    }
    if (dead.length) {
      const byFile = new Map<string, Spot[]>();
      for (const spot of dead) byFile.set(spot.path, [...(byFile.get(spot.path) ?? []), spot]);
      checks.push({
        id: "links",
        label: "Every link goes somewhere",
        level: "warn",
        detail: `${dead.length} link${dead.length === 1 ? " leads" : "s lead"} nowhere: ${dead
          .slice(0, 3)
          .map((spot) => `${spot.code} (${spot.path}:${spot.line})`)
          .join(", ")}${dead.length > 3 ? ` and ${dead.length - 3} more` : ""}`,
        fix: "chat",
        asks: [...byFile].map(
          ([path, spots]) =>
            `In ${path}, ${spots.map((spot) => `the link at line ${spot.line} (${spot.code})`).join(" and ")} ${
              spots.length === 1 ? "goes" : "go"
            } nowhere — a placeholder, a section id that does not exist, or a page that is not in the site. Point each to the right section or page of this site (add the missing section id if that is what was meant), or remove the link if nothing fits.`,
        ),
      });
    } else {
      checks.push({ id: "links", label: "Every link goes somewhere", level: "pass" });
    }
  }

  /* ── Template text still on the page ─────────────────────────────────── */
  {
    const found: { path: string; what: string }[] = [];
    for (const file of pages(files)) {
      const text = visibleText(file.content);
      for (const [pattern, what] of PLACEHOLDER) if (pattern.test(text)) found.push({ path: file.path, what });
    }
    if (found.length) {
      const byFile = new Map<string, string[]>();
      for (const item of found) byFile.set(item.path, [...new Set([...(byFile.get(item.path) ?? []), item.what])]);
      checks.push({
        id: "placeholder",
        label: "No placeholder text",
        level: "warn",
        detail: `Still showing ${[...new Set(found.map((item) => item.what))].join(", ")}.`,
        fix: "chat",
        asks: [...byFile].map(
          ([path, whats]) =>
            `In ${path}, replace the placeholder content still showing (${whats.join(", ")}) with real content for this business — real wording, and contact details taken from elsewhere on the site; where a real detail is unknown, remove that line rather than invent one.`,
        ),
      });
    } else {
      checks.push({ id: "placeholder", label: "No placeholder text", level: "pass" });
    }
  }

  if (!webApp) return checks;

  const mode = backend?.mode && backend.mode !== "none" ? backend.mode : null;
  const usesDatabase = /supabase|createClient\(/i.test(files.map((file) => file.content).join("\n"));
  if (mode) {
    checks.push({ id: "database", label: `Database connected (${DATABASE_LABEL[mode] ?? mode})`, level: "pass" });
    checks.push(
      backend?.ready
        ? { id: "migrations", label: "Database changes applied", level: "pass" }
        : {
            id: "migrations",
            label: "Database changes applied",
            level: "warn",
            detail: "Some database changes haven't been applied yet.",
            fix: "database",
          },
    );
  } else if (usesDatabase) {
    checks.push({
      id: "database",
      label: "Database connected",
      level: "block",
      detail: "This app uses a database and none is connected.",
      fix: "database",
    });
  }

  /* Read by the code, set nowhere: names only. */
  if (secretNames) {
    const read = new Set<string>();
    for (const file of files) {
      for (const match of file.content.matchAll(/process\.env\.([A-Z][A-Z0-9_]*)/g)) read.add(match[1]);
    }
    const set = new Set(secretNames);
    const unset = [...read].filter((name) => !PROVIDED.test(name) && !set.has(name)).sort();
    checks.push(
      unset.length === 0
        ? { id: "env", label: "Environment variables complete", level: "pass" }
        : {
            id: "env",
            label: "Environment variables complete",
            level: "warn",
            detail: `Not set: ${unset.join(", ")}`,
            fix: "database",
          },
    );
  }

  return checks;
}

/** Fetches what the checks need and runs them. Never throws. */
export async function loadChecks(projectId: string, webApp: boolean): Promise<Check[] | null> {
  const json = (url: string) =>
    fetch(url, { cache: "no-store" })
      .then((response) => (response.ok ? response.json() : null))
      .catch(() => null);
  const [files, backend, secrets] = await Promise.all([
    json(`/api/projects/${projectId}/files`),
    webApp ? json(`/api/projects/${projectId}/backend`) : Promise.resolve(null),
    webApp ? json(`/api/projects/${projectId}/secrets`) : Promise.resolve(null),
  ]);
  if (!files || !Array.isArray(files.files)) return null;
  const brokenRemote = await findBrokenImages(files.files as File[]);
  return runChecks({
    files: files.files as File[],
    brokenRemote,
    webApp,
    backend: backend ? { mode: (backend.mode as string | null) ?? null, ready: Boolean(backend.ready) } : null,
    secretNames: secrets && secrets.configured && Array.isArray(secrets.keys) ? (secrets.keys as string[]) : null,
  });
}
